function buildTeam(
  id: number,
  league: string,
  country: string,
  seed: TeamSeed,
): Team {
  const [
    slug,
    name,
    shortName,
    founded,
    stadium,
    stadiumCapacity,
    primaryColor,
    secondaryColor,
  ] = seed;

  const record = standings[leagueSlugByName[league]]?.find(
    (row) => row.teamSlug === slug,
  );

  const wins = record?.wins ?? 0;
  const draws = record?.draws ?? 0;

  return {
    id,
    slug,
    name,
    shortName,
    country,
    league,
    founded,
    stadium,
    stadiumCapacity,
    primaryColor,
    secondaryColor,
    description: `${name} is a professional football club competing in the ${league} in ${country}.`,
    form: record ? [...record.form] : [],
    stats: {
      played: record?.played ?? 0,
      wins,
      draws,
      losses: record?.losses ?? 0,
      goalsScored: record?.goalsFor ?? 0,
      goalsConceded: record?.goalsAgainst ?? 0,
      // Demo estimate, derived so it can never exceed games not lost
      cleanSheets: Math.min(wins + draws, Math.round(wins * 0.6 + draws * 0.3)),
    },
  };
}

const groups: { league: string; country: string; seeds: TeamSeed[] }[] = [
  { league: "Premier League", country: "England", seeds: premierLeague },
  { league: "La Liga", country: "Spain", seeds: laLiga },
  { league: "Serie A", country: "Italy", seeds: serieA },
  { league: "Bundesliga", country: "Germany", seeds: bundesliga },
  { league: "Ligue 1", country: "France", seeds: ligue1 },
];

let nextId = 1;

export const teams: Team[] = groups.flatMap(({ league, country, seeds }) =>
  seeds.map((seed) => buildTeam(nextId++, league, country, seed)),
);
